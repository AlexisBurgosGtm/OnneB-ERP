/**
 * Criterio compartido: ventas netas (facturas − devoluciones) en reportes.
 */
const { STATUS_ANULADO, SQL_TIPODOC_REPORTES_SI } = require('./documento-status');

const { TIPODOC_FPC } = require('./tipodoc-fpc');

const TIPODOC_VENTA = ['FAC', TIPODOC_FPC, 'FEF', 'FEC', 'FES'];
const TIPODOC_DEVOLUCION = ['DEV', 'FNC', 'FNA'];
const TIPODOC_REPORTE = [...TIPODOC_VENTA, ...TIPODOC_DEVOLUCION];

const SQL_TIPODOC_VENTA_IN = TIPODOC_VENTA.map((t) => `'${t}'`).join(', ');
const SQL_TIPODOC_DEV_IN = TIPODOC_DEVOLUCION.map((t) => `'${t}'`).join(', ');
const SQL_TIPODOC_REPORTE_IN = TIPODOC_REPORTE.map((t) => `'${t}'`).join(', ');

/** Filtro documentos para reportes de ventas netas (alias d, t). */
const SQL_REPORTES_VENTAS_WHERE = `
  d.EMPNIT = @EMPNIT
  AND CAST(d.FECHA AS DATE) BETWEEN @DESDE AND @HASTA
  AND ISNULL(d.STATUS, '') <> '${STATUS_ANULADO}'
  AND t.TIPODOC IN (${SQL_TIPODOC_REPORTE_IN})
  AND ${SQL_TIPODOC_REPORTES_SI}
`;

/** Listado de documentos: incluye anulados (importe/costo en cero en la capa de presentación). */
const SQL_REPORTES_VENTAS_WHERE_DOCS = `
  d.EMPNIT = @EMPNIT
  AND CAST(d.FECHA AS DATE) BETWEEN @DESDE AND @HASTA
  AND t.TIPODOC IN (${SQL_TIPODOC_REPORTE_IN})
  AND ${SQL_TIPODOC_REPORTES_SI}
`;

const SQL_SIGNO_DOC_IMPORTE = `
  CASE
    WHEN t.TIPODOC IN (${SQL_TIPODOC_VENTA_IN}) THEN ISNULL(d.TOTALPRECIO, 0)
    WHEN t.TIPODOC IN (${SQL_TIPODOC_DEV_IN}) THEN -ISNULL(d.TOTALPRECIO, 0)
    ELSE 0
  END
`;

const SQL_SIGNO_DOC_COSTO = `
  CASE
    WHEN t.TIPODOC IN (${SQL_TIPODOC_VENTA_IN}) THEN ISNULL(d.TOTALCOSTO, 0)
    WHEN t.TIPODOC IN (${SQL_TIPODOC_DEV_IN}) THEN -ISNULL(d.TOTALCOSTO, 0)
    ELSE 0
  END
`;

/** Importe/costo con signo; anulados (STATUS A) → 0. */
const SQL_DOC_IMPORTE_REPORTE = `
  CASE
    WHEN UPPER(LTRIM(RTRIM(ISNULL(d.STATUS, '')))) = '${STATUS_ANULADO}' THEN 0
    ELSE (${SQL_SIGNO_DOC_IMPORTE})
  END
`;

const SQL_DOC_COSTO_REPORTE = `
  CASE
    WHEN UPPER(LTRIM(RTRIM(ISNULL(d.STATUS, '')))) = '${STATUS_ANULADO}' THEN 0
    ELSE (${SQL_SIGNO_DOC_COSTO})
  END
`;

const SQL_SIGNO_LINEA_UNIDADES = `
  CASE
    WHEN t.TIPODOC IN (${SQL_TIPODOC_VENTA_IN}) THEN ISNULL(dp.TOTALUNIDADES, 0)
    WHEN t.TIPODOC IN (${SQL_TIPODOC_DEV_IN}) THEN -ISNULL(dp.TOTALUNIDADES, 0)
    ELSE 0
  END
`;

const SQL_SIGNO_LINEA_IMPORTE = `
  CASE
    WHEN t.TIPODOC IN (${SQL_TIPODOC_VENTA_IN}) THEN ISNULL(dp.TOTALPRECIO, 0)
    WHEN t.TIPODOC IN (${SQL_TIPODOC_DEV_IN}) THEN -ISNULL(dp.TOTALPRECIO, 0)
    ELSE 0
  END
`;

const SQL_SIGNO_LINEA_COSTO = `
  CASE
    WHEN t.TIPODOC IN (${SQL_TIPODOC_VENTA_IN}) THEN ISNULL(dp.TOTALCOSTO, 0)
    WHEN t.TIPODOC IN (${SQL_TIPODOC_DEV_IN}) THEN -ISNULL(dp.TOTALCOSTO, 0)
    ELSE 0
  END
`;

const SQL_JOIN_DOC_LINEAS = `
  INNER JOIN dbo.DOCUMENTOS d
    ON dp.EMPNIT = d.EMPNIT AND dp.CODDOC = d.CODDOC AND dp.CORRELATIVO = d.CORRELATIVO
  INNER JOIN dbo.TIPODOCUMENTOS t ON t.EMPNIT = d.EMPNIT AND t.CODDOC = d.CODDOC
`;

module.exports = {
  TIPODOC_VENTA,
  TIPODOC_DEVOLUCION,
  TIPODOC_REPORTE,
  SQL_TIPODOC_VENTA_IN,
  SQL_TIPODOC_DEV_IN,
  SQL_TIPODOC_REPORTE_IN,
  SQL_REPORTES_VENTAS_WHERE,
  SQL_REPORTES_VENTAS_WHERE_DOCS,
  SQL_SIGNO_DOC_IMPORTE,
  SQL_SIGNO_DOC_COSTO,
  SQL_DOC_IMPORTE_REPORTE,
  SQL_DOC_COSTO_REPORTE,
  SQL_SIGNO_LINEA_UNIDADES,
  SQL_SIGNO_LINEA_IMPORTE,
  SQL_SIGNO_LINEA_COSTO,
  SQL_JOIN_DOC_LINEAS,
};
