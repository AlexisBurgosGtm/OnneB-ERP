-- @UPDATER_CHUNK CONSULTORIO_PACIENTES_TABLE
/* MODULO:CONSULTORIO:PACIENTES_TABLE */
IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'CONSULTORIO_PACIENTES' AND schema_id = SCHEMA_ID('dbo'))
BEGIN
  CREATE TABLE dbo.CONSULTORIO_PACIENTES (
    EMPNIT VARCHAR(50) NOT NULL,
    CODPACIENTE INT NOT NULL,
    NOMBRE VARCHAR(200) NOT NULL,
    DIRECCION VARCHAR(500) NULL,
    TELEFONOS VARCHAR(200) NULL,
    EMAIL VARCHAR(200) NULL,
    NOTAS VARCHAR(MAX) NULL,
    HIPERTENSION VARCHAR(2) NOT NULL CONSTRAINT DF_CONS_PAC_HIPERTENSION DEFAULT ('NO'),
    HIPOTENSION VARCHAR(2) NOT NULL CONSTRAINT DF_CONS_PAC_HIPOTENSION DEFAULT ('NO'),
    DIABETES VARCHAR(2) NOT NULL CONSTRAINT DF_CONS_PAC_DIABETES DEFAULT ('NO'),
    INSUFICIENCIA_RENAL VARCHAR(2) NOT NULL CONSTRAINT DF_CONS_PAC_INSUFREN DEFAULT ('NO'),
    CARDIOPATIAS VARCHAR(2) NOT NULL CONSTRAINT DF_CONS_PAC_CARDIO DEFAULT ('NO'),
    TAQUICARDIAS VARCHAR(2) NOT NULL CONSTRAINT DF_CONS_PAC_TAQUI DEFAULT ('NO'),
    HIGADOGRASO VARCHAR(2) NOT NULL CONSTRAINT DF_CONS_PAC_HIGADO DEFAULT ('NO'),
    HISTERECTOMIA VARCHAR(2) NOT NULL CONSTRAINT DF_CONS_PAC_HISTER DEFAULT ('NO'),
    COLESISTECTOMIA VARCHAR(2) NOT NULL CONSTRAINT DF_CONS_PAC_COLE DEFAULT ('NO'),
    ALERGIAS VARCHAR(2) NOT NULL CONSTRAINT DF_CONS_PAC_ALERG DEFAULT ('NO'),
    CONSTRAINT PK_CONSULTORIO_PACIENTES PRIMARY KEY (EMPNIT, CODPACIENTE),
    CONSTRAINT CK_CONS_PAC_HIPERTENSION CHECK (HIPERTENSION IN ('SI', 'NO')),
    CONSTRAINT CK_CONS_PAC_HIPOTENSION CHECK (HIPOTENSION IN ('SI', 'NO')),
    CONSTRAINT CK_CONS_PAC_DIABETES CHECK (DIABETES IN ('SI', 'NO')),
    CONSTRAINT CK_CONS_PAC_INSUFREN CHECK (INSUFICIENCIA_RENAL IN ('SI', 'NO')),
    CONSTRAINT CK_CONS_PAC_CARDIO CHECK (CARDIOPATIAS IN ('SI', 'NO')),
    CONSTRAINT CK_CONS_PAC_TAQUI CHECK (TAQUICARDIAS IN ('SI', 'NO')),
    CONSTRAINT CK_CONS_PAC_HIGADO CHECK (HIGADOGRASO IN ('SI', 'NO')),
    CONSTRAINT CK_CONS_PAC_HISTER CHECK (HISTERECTOMIA IN ('SI', 'NO')),
    CONSTRAINT CK_CONS_PAC_COLE CHECK (COLESISTECTOMIA IN ('SI', 'NO')),
    CONSTRAINT CK_CONS_PAC_ALERG CHECK (ALERGIAS IN ('SI', 'NO'))
  );
  CREATE INDEX IX_CONSULTORIO_PACIENTES_EMP_NOMBRE
    ON dbo.CONSULTORIO_PACIENTES (EMPNIT, NOMBRE);
END;

