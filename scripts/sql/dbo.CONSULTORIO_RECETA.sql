-- @UPDATER_CHUNK CONSULTORIO_RECETA_TIPODOC_CONFIG
/* MODULO:CONSULTORIO:RECETA_TIPODOC_CONFIG */
IF NOT EXISTS (
  SELECT 1 FROM dbo.CONFIG_TIPODOCUMENTOS
  WHERE UPPER(LTRIM(RTRIM(TIPODOC))) = 'REC'
)
BEGIN
  INSERT INTO dbo.CONFIG_TIPODOCUMENTOS (TIPODOC, DESCRIPCION)
  VALUES ('REC', 'RECETAS MEDICAS');
END;

-- @UPDATER_CHUNK CONSULTORIO_CONSULTAS_RECETA_LINK
/* MODULO:CONSULTORIO:CONSULTAS_RECETA_LINK */
IF COL_LENGTH('dbo.CONSULTORIO_CONSULTAS', 'CODDOC_RECETA') IS NULL
BEGIN
  ALTER TABLE dbo.CONSULTORIO_CONSULTAS ADD CODDOC_RECETA VARCHAR(20) NULL;
END;
IF COL_LENGTH('dbo.CONSULTORIO_CONSULTAS', 'CORRELATIVO_RECETA') IS NULL
BEGIN
  ALTER TABLE dbo.CONSULTORIO_CONSULTAS ADD CORRELATIVO_RECETA DECIMAL(18, 0) NULL;
END;