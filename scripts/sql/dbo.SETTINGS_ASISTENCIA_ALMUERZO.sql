-- SETTINGS — registrar almuerzo en control de asistencia (SI/NO)
-- @UPDATER_CHUNK SETTINGS_CONTROL_ASISTENCIA_ALMUERZO
IF NOT EXISTS (
  SELECT 1 FROM dbo.SETTINGS WHERE OPCION = N'CONTROL ASISTENCIA ALMUERZO'
)
BEGIN
  INSERT INTO dbo.SETTINGS (OPCION, VALOR) VALUES (N'CONTROL ASISTENCIA ALMUERZO', N'NO');
END;
