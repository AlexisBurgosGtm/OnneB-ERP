IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'FEL_ADENDAS_PERSO' AND schema_id = SCHEMA_ID('dbo'))
BEGIN
  CREATE TABLE dbo.FEL_ADENDAS_PERSO (
    EMPNIT VARCHAR(50) NOT NULL,
    SLOT_NUM TINYINT NOT NULL,
