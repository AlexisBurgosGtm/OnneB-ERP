-- Uso: node scripts/seed-update-query-invsaldo-lote.js → Actualizador BD

-- @UPDATER_CHUNK PRODUCTOS_USA_LOTES
IF COL_LENGTH('dbo.PRODUCTOS', 'USA_LOTES') IS NULL
BEGIN
  ALTER TABLE dbo.PRODUCTOS ADD USA_LOTES VARCHAR(2) NOT NULL
    CONSTRAINT DF_PRODUCTOS_USA_LOTES DEFAULT ('NO') WITH VALUES;
END;

-- @UPDATER_CHUNK DOCPRODUCTOS_NOLOTE
IF COL_LENGTH('dbo.DOCPRODUCTOS', 'NOLOTE') IS NULL
BEGIN
  ALTER TABLE dbo.DOCPRODUCTOS ADD NOLOTE NVARCHAR(50) NULL;
END;

-- @UPDATER_CHUNK DOCPRODUCTOS_FVENCLOTE
IF COL_LENGTH('dbo.DOCPRODUCTOS', 'FVENCLOTE') IS NULL
BEGIN
  ALTER TABLE dbo.DOCPRODUCTOS ADD FVENCLOTE DATE NULL;
END;

-- @UPDATER_CHUNK INVSALDO_LOTE_TABLE
IF OBJECT_ID('dbo.INVSALDO_LOTE', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.INVSALDO_LOTE (
    ID INT IDENTITY(1, 1) NOT NULL,
    EMPNIT VARCHAR(20) NOT NULL,
    CODPROD VARCHAR(50) NOT NULL,
    CODBODEGA INT NOT NULL CONSTRAINT DF_INVSALDO_LOTE_CODBODEGA DEFAULT (0),
    NOLOTE NVARCHAR(50) NOT NULL,
    FVENCLOTE DATE NULL,
    SALDO FLOAT NOT NULL CONSTRAINT DF_INVSALDO_LOTE_SALDO DEFAULT (0),
    FISICO FLOAT NULL,
    CONSTRAINT PK_INVSALDO_LOTE PRIMARY KEY CLUSTERED (ID)
  );
  CREATE UNIQUE INDEX UX_INVSALDO_LOTE_KEY
    ON dbo.INVSALDO_LOTE (EMPNIT, CODPROD, CODBODEGA, NOLOTE);
END;
