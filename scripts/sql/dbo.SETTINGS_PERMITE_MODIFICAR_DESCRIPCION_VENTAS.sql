-- SETTINGS.OPCION — ampliar si la columna es corta (evita truncado al guardar SI/NO)
-- @UPDATER_CHUNK SettingsOpcionColumnWiden
IF COL_LENGTH('dbo.SETTINGS', 'OPCION') IS NOT NULL
   AND COL_LENGTH('dbo.SETTINGS', 'OPCION') < 80
BEGIN
  ALTER TABLE dbo.SETTINGS ALTER COLUMN OPCION NVARCHAR(80) NOT NULL;
END
GO

-- @UPDATER_CHUNK SettingsPermiteModificarDescripcionVentas
IF EXISTS (
  SELECT 1 FROM dbo.SETTINGS
  WHERE OPCION = N'PERMITE MODIFICAR DESCRIPCION DE PRODUCTO EN VENTAS'
)
BEGIN
  UPDATE dbo.SETTINGS
  SET OPCION = N'PERMITE MODIFICAR DESCR VENTAS'
  WHERE OPCION = N'PERMITE MODIFICAR DESCRIPCION DE PRODUCTO EN VENTAS';
END
GO

IF NOT EXISTS (
  SELECT 1 FROM dbo.SETTINGS WHERE OPCION = N'PERMITE MODIFICAR DESCR VENTAS'
)
BEGIN
  INSERT INTO dbo.SETTINGS (OPCION, VALOR) VALUES (N'PERMITE MODIFICAR DESCR VENTAS', N'NO');
END
GO
