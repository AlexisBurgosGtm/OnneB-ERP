-- LASTUPDATE en PRODUCTOS: fecha de última modificación del maestro (catálogo / sync).

-- @UPDATER_CHUNK PRODUCTOS_LASTUPDATE
IF OBJECT_ID(N'dbo.PRODUCTOS', N'U') IS NOT NULL
  AND COL_LENGTH(N'dbo.PRODUCTOS', N'LASTUPDATE') IS NULL
BEGIN
  ALTER TABLE dbo.PRODUCTOS ADD LASTUPDATE DATE NULL;
END;
