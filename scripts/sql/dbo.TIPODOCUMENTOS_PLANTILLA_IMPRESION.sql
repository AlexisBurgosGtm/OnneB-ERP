-- @UPDATER_CHUNK TIPODOCUMENTOS_NOMBRE_PLANTILLA_IMPRESION
IF COL_LENGTH('dbo.TIPODOCUMENTOS', 'NOMBRE_PLANTILLA_IMPRESION') IS NULL
BEGIN
  ALTER TABLE dbo.TIPODOCUMENTOS
    ADD NOMBRE_PLANTILLA_IMPRESION VARCHAR(100) NULL;
END;

-- @UPDATER_CHUNK FORMATOS_IMPRESION_UQ_POR_NOMBRE
IF OBJECT_ID('dbo.FORMATOS_IMPRESION', 'U') IS NOT NULL
BEGIN
  IF EXISTS (
    SELECT 1 FROM sys.key_constraints
    WHERE name = 'UQ_FORMATOS_IMPRESION'
      AND parent_object_id = OBJECT_ID('dbo.FORMATOS_IMPRESION')
  )
  BEGIN
    ALTER TABLE dbo.FORMATOS_IMPRESION DROP CONSTRAINT UQ_FORMATOS_IMPRESION;
  END;

  IF NOT EXISTS (
    SELECT 1 FROM sys.key_constraints
    WHERE name = 'UQ_FORMATOS_IMPRESION_NOMBRE'
      AND parent_object_id = OBJECT_ID('dbo.FORMATOS_IMPRESION')
  )
  BEGIN
    ALTER TABLE dbo.FORMATOS_IMPRESION
      ADD CONSTRAINT UQ_FORMATOS_IMPRESION_NOMBRE
      UNIQUE (EMPNIT, TIPODOC, PAPEL, NOMBRE);
  END;
END;
