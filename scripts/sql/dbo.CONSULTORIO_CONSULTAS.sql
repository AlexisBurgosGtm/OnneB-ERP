-- @UPDATER_CHUNK CONSULTORIO_CONSULTAS_TABLE
/* MODULO:CONSULTORIO:CONSULTAS_TABLE */
IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'CONSULTORIO_CONSULTAS' AND schema_id = SCHEMA_ID('dbo'))
BEGIN
  CREATE TABLE dbo.CONSULTORIO_CONSULTAS (
    EMPNIT VARCHAR(50) NOT NULL,
    CODCONSULTA INT NOT NULL,
    CODPACIENTE INT NOT NULL,
    TIPO VARCHAR(30) NOT NULL,
    FECHA DATE NOT NULL,
    HORA VARCHAR(8) NOT NULL,
    MOTIVO VARCHAR(500) NULL,
    SINTOMAS VARCHAR(MAX) NULL,
    PA VARCHAR(20) NULL,
    FC INT NULL,
    FR INT NULL,
    TEMPERATURA NUMERIC(5, 2) NULL,
    PESO NUMERIC(8, 3) NULL,
    TALLA INT NULL,
    IMPRESION_DIAGNOSTICA VARCHAR(MAX) NULL,
    TRATAMIENTO VARCHAR(MAX) NULL,
    CONSTRAINT PK_CONSULTORIO_CONSULTAS PRIMARY KEY (EMPNIT, CODCONSULTA),
    CONSTRAINT CK_CONSULTORIO_CONSULTAS_TIPO CHECK (
      TIPO IN ('GENERAL', 'GINECOLOGICA', 'DERMATOLOGIA', 'PEDIATRIA')
    )
  );
  CREATE INDEX IX_CONSULTORIO_CONSULTAS_EMP_FECHA
    ON dbo.CONSULTORIO_CONSULTAS (EMPNIT, FECHA DESC, HORA DESC);
  CREATE INDEX IX_CONSULTORIO_CONSULTAS_PACIENTE
    ON dbo.CONSULTORIO_CONSULTAS (EMPNIT, CODPACIENTE);
END;